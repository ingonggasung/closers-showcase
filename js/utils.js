// Escapes text before it's interpolated into an innerHTML template.
// Needed anywhere user-supplied content (names, titles) is shown to other visitors.
function escapeHtml(str) {
  return String(str ?? '').replace(/[&<>"']/g, (ch) => ({
    '&': '&amp;',
    '<': '&lt;',
    '>': '&gt;',
    '"': '&quot;',
    "'": '&#39;',
  }[ch]));
}
